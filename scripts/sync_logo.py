"""
This script keeps every OpenMCAT logo surface consistent with ./assets/logo.svg.

./assets/logo.svg is the single source of the logo. This script copies the shapes inside its
<g id="openmcat-logo"> group into the other logo surfaces:
- ./index.html: the header brand mark between the openmcat-logo marker comments.
- ./src/components/logo.js: the shapes used by the About page.
- ./assets/favicon.svg: the logo on a rounded tile, with the colors from ./assets/logo.svg.

Usage:
- Rewrite any surface that is out of sync: python scripts/sync_logo.py
- Report out-of-sync surfaces and exit 1 without writing: python scripts/sync_logo.py --check
"""

import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOGO_PATH = ROOT / "assets" / "logo.svg"
INDEX_PATH = ROOT / "index.html"
MODULE_PATH = ROOT / "src" / "components" / "logo.js"
FAVICON_PATH = ROOT / "assets" / "favicon.svg"
INDEX_START = "<!-- openmcat-logo:start -->"
INDEX_END = "<!-- openmcat-logo:end -->"
INDENT = "    "

class SyncError(Exception):
    pass

def read_text(path):
    try:
        return path.read_text(encoding="utf-8")
    except FileNotFoundError:
        raise SyncError(f"{path.relative_to(ROOT)} does not exist")

def parse_logo(source):
    view_box_match = re.search(r'<svg\b[^>]*\bviewBox="([^"]+)"', source)
    if not view_box_match:
        raise SyncError("./assets/logo.svg has no viewBox on its <svg> element")
    view_box = view_box_match.group(1)
    values = view_box.split()
    if len(values) != 4 or values[2] != values[3]:
        raise SyncError(f'./assets/logo.svg must have a square viewBox, found "{view_box}"')
    style_match = re.search(r"<style>\n(.*?)\n\s*</style>", source, re.S)
    if not style_match:
        raise SyncError("./assets/logo.svg has no <style> block")
    style_lines = textwrap.dedent(style_match.group(1)).strip("\n").split("\n")
    group_match = re.search(r'<g id="openmcat-logo">\n(.*?)\n\s*</g>', source, re.S)
    if not group_match:
        raise SyncError('./assets/logo.svg has no <g id="openmcat-logo"> group')
    shapes = [line.strip() for line in group_match.group(1).split("\n") if line.strip()]
    if not shapes:
        raise SyncError('the <g id="openmcat-logo"> group in ./assets/logo.svg is empty')
    for shape in shapes:
        if not re.fullmatch(r"<\w+\b[^<>]*/>", shape):
            raise SyncError(f"each logo shape must be one self-closing element on its own line, found: {shape}")
        if re.search(r"\bid=", shape):
            raise SyncError(f"logo shapes must not have ids, because they are copied into pages more than once: {shape}")
        if "'" in shape or "\\" in shape:
            raise SyncError(f"logo shapes must not contain single quotes or backslashes: {shape}")
    return view_box, style_lines, shapes

def render_index(current, view_box, shapes):
    pattern = re.compile(r"^([ \t]*)" + re.escape(INDEX_START) + r"\n.*?^[ \t]*" + re.escape(INDEX_END), re.S | re.M)
    match = pattern.search(current)
    if not match:
        raise SyncError(f"./index.html needs the {INDEX_START} and {INDEX_END} marker comments around the header brand mark")
    indent = match.group(1)
    lines = [
        f"{indent}{INDEX_START}",
        f'{indent}<svg class="brand-mark" width="32" height="32" viewBox="{view_box}" aria-hidden="true" focusable="false">',
        *(f"{indent}{INDENT}{shape}" for shape in shapes),
        f"{indent}</svg>",
        f"{indent}{INDEX_END}"
    ]
    return current[:match.start()] + "\n".join(lines) + current[match.end():]

def render_module(view_box, shapes):
    lines = [
        "// Generated by ./scripts/sync_logo.py from ./assets/logo.svg. Do not edit this file by hand. Run `npm run sync:logo` instead.",
        "",
        f'export const LOGO_VIEW_BOX = "{view_box}";',
        "",
        "export const LOGO_SHAPES = [",
        ",\n".join(f"{INDENT}'{shape}'" for shape in shapes),
        '].join("");',
        ""
    ]
    return "\n".join(lines)

def render_favicon(view_box, style_lines, shapes):
    size = view_box.split()[2]
    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view_box}" role="img" aria-labelledby="openmcat-favicon-title">',
        f"{INDENT}<title id=\"openmcat-favicon-title\">OpenMCAT</title>",
        f"{INDENT}<style>",
        f"{INDENT * 2}.openmcat-favicon-tile {{ fill: #14130F; }}",
        f"{INDENT * 2}@media (prefers-color-scheme: light) {{",
        f"{INDENT * 3}.openmcat-favicon-tile {{ fill: #F4EEDF; }}",
        f"{INDENT * 2}}}",
        *(f"{INDENT * 2}{line}" if line else "" for line in style_lines),
        f"{INDENT}</style>",
        f'{INDENT}<rect class="openmcat-favicon-tile" width="{size}" height="{size}" rx="4"/>',
        f'{INDENT}<g transform="translate(2 2) scale(0.875)">',
        *(f"{INDENT * 2}{shape}" for shape in shapes),
        f"{INDENT}</g>",
        "</svg>",
        ""
    ]
    return "\n".join(lines)

def main(argv):
    check_only = "--check" in argv
    unknown = [arg for arg in argv if arg != "--check"]
    if unknown:
        print(f"Unknown argument: {unknown[0]}\nUsage: python scripts/sync_logo.py [--check]", file=sys.stderr)
        return 2
    try:
        view_box, style_lines, shapes = parse_logo(read_text(LOGO_PATH))
        index_current = read_text(INDEX_PATH)
        targets = [
            (INDEX_PATH, index_current, render_index(index_current, view_box, shapes)),
            (MODULE_PATH, MODULE_PATH.read_text(encoding="utf-8") if MODULE_PATH.exists() else None, render_module(view_box, shapes)),
            (FAVICON_PATH, FAVICON_PATH.read_text(encoding="utf-8") if FAVICON_PATH.exists() else None, render_favicon(view_box, style_lines, shapes))
        ]
    except SyncError as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1
    stale = [(path, expected) for path, current, expected in targets if current != expected]
    for path, expected in stale:
        relative = path.relative_to(ROOT).as_posix()
        if check_only:
            print(f"Out of sync: {relative}")
        else:
            path.write_text(expected, encoding="utf-8", newline="\n")
            print(f"Updated: {relative}")
    if check_only and stale:
        print("Run `npm run sync:logo` to update them.")
        return 1
    if not stale:
        print("All logo surfaces are in sync with ./assets/logo.svg.")
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
